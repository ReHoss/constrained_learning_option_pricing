r"""Validate the closed-form Reiner-Rubinstein Gamma against finite differences.

Compares :func:`learning_option_pricing.pricing.barrier.reiner_rubinstein_down_and_out_put_gamma`
(the analytic :math:`\partial_{ss}V_{DO}`, derived by differentiating the
Reiner-Rubinstein price term by term -- a combination of vanilla Black-Scholes
Gammas plus the chain-rule terms generated by the reflection prefactor
:math:`(B/s)^{2\nu/\sigma^2}` and the reflected spot :math:`B^2/s`) against a
central second finite difference of the price itself,
:func:`~learning_option_pricing.pricing.barrier.reiner_rubinstein_down_and_out_put`.

Every closed form used by the analytic Gamma was already checked, during
development, against sympy's own symbolic second derivative of the exact same
expression the price function evaluates (simplify-to-zero, i.e. an exact
symbolic match, not a numerical one). This script is the complementary
*numerical* check the task asked for: does the closed form agree with a
finite-difference estimate computed from the already-tested price function.

Does not train or fit anything -- pure closed-form evaluation.

Usage:
    python3 experiments/python_scripts/exp_barrier_option/diagnostic_scripts/\
validate_reiner_rubinstein_gamma.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))

import matplotlib.pyplot as plt  # noqa: E402

from learning_option_pricing.pricing.barrier import (  # noqa: E402
    reiner_rubinstein_down_and_out_put,
    reiner_rubinstein_down_and_out_put_gamma,
)
from learning_option_pricing.utils.figure_layout import finalize_figure  # noqa: E402
from learning_option_pricing.utils.run_context import script_data_dir  # noqa: E402

K, B, r, sigma = 100.0, 80.0, 0.02, 0.25
H = 1e-2  # finite-difference step
TAU_VALUES = [0.05, 0.25, 1.0, 2.0]

FORMULA_TEXT = (
    r"$V_{DO}(s,\tau)=\mathrm{TP}(s)-(B/s)^{2\nu/\sigma^2}\mathrm{TP}(B^2/s)$,  "
    r"$\Gamma(x,\mathrm{strike})=N'(d_+(x,\mathrm{strike}))/(x\sigma\sqrt{\tau})$"
    "\n"
    r"$\partial_{ss}V_{DO}=\mathrm{TP}''(s)-\left[w''\mathrm{TP}(x_2)+2w'\mathrm{TP}'(x_2)x_2'"
    r"+w\,\mathrm{TP}''(x_2)(x_2')^2+w\,\mathrm{TP}'(x_2)x_2''\right]$"
    "\n"
    r"$w(s)=(B/s)^{2\nu/\sigma^2}$, $x_2(s)=B^2/s$ (reflection prefactor / reflected spot, chain rule)"
)


def main() -> None:
    s_vals = torch.linspace(B + 2.0, K * 2.0, 200, dtype=torch.float64)

    fig, axes = plt.subplots(1, 2, figsize=(13.5, 5.0))
    ax_overlay, ax_error = axes

    colors = plt.cm.viridis(np.linspace(0.15, 0.85, len(TAU_VALUES)))
    max_abs_err_overall = 0.0

    for color, tau_val in zip(colors, TAU_VALUES):
        tau = torch.full_like(s_vals, tau_val)

        analytic_gamma = reiner_rubinstein_down_and_out_put_gamma(s_vals, K, B, r, sigma, tau)

        price_plus = reiner_rubinstein_down_and_out_put(s_vals + H, K, B, r, sigma, tau)
        price_mid = reiner_rubinstein_down_and_out_put(s_vals, K, B, r, sigma, tau)
        price_minus = reiner_rubinstein_down_and_out_put(s_vals - H, K, B, r, sigma, tau)
        fd_gamma = (price_plus - 2 * price_mid + price_minus) / H**2

        abs_err = (fd_gamma - analytic_gamma).abs()
        max_abs_err_overall = max(max_abs_err_overall, float(abs_err.max()))

        ax_overlay.plot(s_vals.numpy(), analytic_gamma.numpy(), color=color, lw=2.0,
                         label=fr"$\tau={tau_val:g}$ (analytic)")
        ax_overlay.plot(s_vals.numpy(), fd_gamma.numpy(), color=color, lw=1.0, linestyle="--",
                         label=fr"$\tau={tau_val:g}$ (finite diff.)")
        ax_error.semilogy(s_vals.numpy(), np.maximum(abs_err.numpy(), 1e-20), color=color, lw=1.5,
                           label=fr"$\tau={tau_val:g}$")

        print(f"tau={tau_val:<5g}  max|analytic - finite-diff|(absolute) = {float(abs_err.max()):.3e}")

    ax_overlay.axvline(B, color="black", linestyle=":", linewidth=1.0)
    ax_overlay.set_xlabel("Underlying price $s$")
    ax_overlay.set_ylabel(r"$\partial_{ss}V_{DO}(s,\tau)$")
    ax_overlay.set_title("Analytic Gamma vs. finite differences", fontsize=11)
    ax_overlay.grid(alpha=0.3)
    legend1 = ax_overlay.legend(loc="upper right", fontsize=7, ncol=2)

    ax_error.axvline(B, color="black", linestyle=":", linewidth=1.0)
    ax_error.set_xlabel("Underlying price $s$")
    ax_error.set_ylabel(r"$|\Gamma_{\mathrm{analytic}} - \Gamma_{\mathrm{finite\,diff.}}|$  (log scale)")
    ax_error.set_title(f"Absolute error (finite-diff. step $h={H:g}$)", fontsize=11)
    ax_error.grid(alpha=0.3, which="both")
    legend2 = ax_error.legend(loc="upper right", fontsize=8)

    fig.suptitle(
        f"Reiner-Rubinstein Gamma: closed form vs. central finite differences  (K={K:g}, B={B:g}, r={r:g}, sigma={sigma:g})",
        fontsize=12,
    )
    fig.subplots_adjust(bottom=0.30, top=0.86, wspace=0.28)
    out_dir = script_data_dir(Path(__file__).resolve().parents[1] / "pilot_down_and_out_put.py") / "diagnostics"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / "reiner_rubinstein_gamma_validation.png"
    finalize_figure(fig, out_path, legends=[legend1, legend2], formula=FORMULA_TEXT, axes=list(axes))
    print(f"\nOverall max absolute error (all tau, all s): {max_abs_err_overall:.3e}")
    print(f"Figure saved -> {out_path}")


if __name__ == "__main__":
    main()
